#!/usr/bin/env node
// Builds the SQL seed for private.legal_documents from docs/legal/*.md.
//
//   node docs/legal/build-seed.mjs > supabase/migrations/<timestamp>_<name>.sql
//
// Documents are inserted as drafts (published_at = null). Publishing is a
// separate, explicit service-role step (see docs/legal/open-questions.md).
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const LEGAL_KINDS = ["terms", "privacy", "kvkk", "community_rules"];

export function parseLegalMarkdown(text) {
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text.replace(/\r\n/g, "\n"));
  if (!match) throw new Error("Missing front matter");
  const meta = Object.fromEntries(
    match[1].split("\n").map((line) => {
      const index = line.indexOf(":");
      return [line.slice(0, index).trim(), line.slice(index + 1).trim()];
    }),
  );
  return { kind: meta.kind, version: meta.version, title: meta.title, body: match[2].trim() };
}

export function loadLegalDocuments() {
  return LEGAL_KINDS.map((kind) => {
    const doc = parseLegalMarkdown(readFileSync(join(here, `${kind}.md`), "utf8"));
    if (doc.kind !== kind) throw new Error(`${kind}.md declares kind ${doc.kind}`);
    if (/\b(TODO|TBD|lorem|XXX)\b|\[[^\]]*doğrulan/i.test(doc.body))
      throw new Error(`${kind}.md contains placeholder text`);
    return doc;
  });
}

const dollar = (value, tag) => {
  if (value.includes(`$${tag}$`)) throw new Error(`Body contains delimiter ${tag}`);
  return `$${tag}$${value}$${tag}$`;
};

export function buildSeedSql(documents = loadLegalDocuments()) {
  const rows = documents.map(
    (doc) =>
      `  (${dollar(doc.kind, "k")}, ${dollar(doc.version, "v")}, ${dollar(doc.title, "t")},\n   ${dollar(doc.body, "legal_body")})`,
  );
  return `-- Generated by docs/legal/build-seed.mjs from docs/legal/*.md. Do not edit by hand.
-- Drafts only: published_at stays NULL until the owner resolves
-- docs/legal/open-questions.md and runs private.publish_legal_document(...).
insert into private.legal_documents (kind, version, title, body)
values
${rows.join(",\n")}
on conflict (kind, version) do nothing;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(buildSeedSql());
